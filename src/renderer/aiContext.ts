interface ProjectMeta { name?: string; description?: string; kind?: string; siteType?: string; base?: string; target?: string }

const SITE_TYPE_LABEL: Record<string, string> = {
  lp: 'LP（1ページ）',
  shop: '会社・お店のサイト',
  portfolio: 'ポートフォリオ',
  blog: 'ブログ風サイト',
}

/** プロジェクトの概要（名前・説明・公開先・ファイル構成）を文字列化する */
export async function buildProjectContext(dir: string | null | undefined): Promise<string> {
  if (!dir) return ''
  let meta: ProjectMeta = {}
  try {
    const raw = await window.electronAPI.fs.readFile(`${dir}/.sakuraide.json`)
    meta = JSON.parse(raw)
  } catch { /* メタ無し（既存フォルダを開いた場合など） */ }

  let files: string[] = []
  try { files = await window.electronAPI.fs.projectFiles(dir) } catch {}

  const name = meta.name || dir.split('/').pop() || ''
  const fileList = files.length ? files.map(f => `- ${f}`).join('\n') : '（まだファイルはありません）'

  // 公開先プロファイル（その環境でうまくいく構成の知識）を注入する
  const profileBlock = '\n' + profileToContext(getTargetProfile(meta.target)) + '\n'

  return (
    '# 現在のプロジェクト\n' +
    `名前: ${name}\n` +
    (meta.kind === 'site'
      ? `種別: Webサイト${meta.siteType ? `（${SITE_TYPE_LABEL[meta.siteType] ?? meta.siteType}）` : ''}\n`
      : meta.kind === 'app' ? '種別: アプリ\n' : '') +
    (meta.description ? `概要: ${meta.description}\n` : '') +
    (meta.target ? `公開先: ${TARGET_LABEL[meta.target] ?? meta.target}\n` : '') +
    profileBlock +
    `ルートパス: ${dir}\n` +
    'ファイル構成:\n' +
    fileList +
    '\n\nユーザーの要望に沿って、上記プロジェクトの開発を進めてください。'
  )
}
