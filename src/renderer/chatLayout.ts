// chatLayout.ts — チャット欄の縦の寸法の決まり（P-141）。
//
// 入力欄の上に置く案内（🧹 フォルダを整理する）は flex-none で高さの上限が無く、窓が低い（CSS 625px）と
// 会話の枠を 43px まで押しつぶした。「✋ 毎回確認」の札の【許可する】【拒否】が枠の上に隠れて押せなくなった
// （0.6.38 の実機）。案内の高さに上限を付け、会話の枠に最小の高さを付ける。

/**
 * 入力欄の上の案内の枠。画面の高さの 30% を上限にし、超えたら案内の中で送る。
 * flex-none にしない（rc39-D1）: 縮めない枠だと、窓が低いとき（CSS 625px）見出し・会話の最小・案内・入力欄の
 * 合計が欄を超え、欄全体が縦に送れて【送信】の下が欠けた。shrink と min-h-0 で、残りの高さまで案内が縮んで中で送る。
 */
export const CHAT_NOTICE_CLASS = 'shrink min-h-0 max-h-[30vh] overflow-y-auto'

/** 会話（札が出る枠）。これより低くはしない。札が出たときの「末尾へ送る」が狭くても効く。 */
export const CHAT_LIST_MIN_CLASS = 'min-h-[140px]'
