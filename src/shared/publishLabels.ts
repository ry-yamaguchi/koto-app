// publishLabels.ts — 公開ボタンの文言を1箇所に決める（委譲仕様 UX-E・判断8）。
//
// これまで HANAMII は「再公開する」、AppRun 共用型は「公開する（作成・更新）」、
// Vercel・AppRun 専有型は「公開する」と、同じ操作（公開する）に別々の言い方をしていた。
// **全パネルの主ボタンは「🚀 公開する」に揃え、既に公開済み（今回は更新になる）ときだけ
// 「（更新）」を付ける。** 専有型の⑤「クラスタを作成する」はクラスタの作成であって
// 公開（アプリケーションの公開）ではないため、この関数の対象外（呼び出さない）。
export function publishButtonLabel(published: boolean): string {
  return published ? '🚀 公開する（更新）' : '🚀 公開する'
}

// publishFailureHintText — 公開の失敗結果に付く `hint`（main の imagePublish.ts が判断）の
// 案内文を1箇所に決める（D-4f）。
//
// 共用型 AppRunPanel.tsx は hint:'reset-registry' のとき「↻ レジストリを設定し直す」ボタンを
// その場に出す（autoCreateRegistry で直接直せる）。専有型タブ（AppRunDedicatedPanel.tsx）には
// そのボタンが無い（レジストリの用意・作り直しは共用型タブの導線しか無い）ため、同じボタンを
// 複製せず、共用型タブへ誘導する1文だけを出す。文言は共用型の同じ hint の説明
// （「このプロジェクトのコンテナレジストリを探し直し…」）と揃えた。
export function publishFailureHintText(hint: string | undefined): string | null {
  if (hint === 'reset-registry') {
    return 'イメージの置き場（コンテナレジストリ）の接続情報が古い可能性があります。共用型タブの「レジストリを設定し直す」を押してから、もう一度お試しください。'
  }
  return null
}

// dnsGuidanceLines — 専有型⑧の DNS 案内文を1箇所に決める（D-4h・2026-09-16 実機で判明）。
//
// 専有型のロードバランサは「入力されたホスト名」でアプリを振り分ける（さくらのマニュアル
// 「入力したホスト名でロードバランサにアクセスした場合、このアプリケーションにルーティングされます」）。
// そのため IP を直接ブラウザで開くと、ロードバランサが 404 page not found を返す
// （アプリの不調ではない。実際に Ryosuke さんが実機でこれに当たった）。
// また https は、DNS の A レコードが向いてから Let's Encrypt が証明書を発行するまでは開けない
// （HTTP-01 チャレンジのため）。
// 「公開中」の下の常時表示と、公開結果の案内の2か所で同じ趣旨の文言を出すため、
// 判断をここへ集約する（掟10・同じ文字列を2か所に書かない）。呼び出し側はこれを描くだけにする。
//
// ── 所要時間を断定しない（D-13 B・2026-09-16）───────────────────────────────────
// ここだけが「A レコードを向けてから**数分で**使えるようになります」と断定しており、
// README・使い方ガイド・CHANGELOG・計画書（「発行にかかる時間は確認できていない」）と
// 食い違っていた。**画面の文言だけが断定している**状態で、しかも画面は利用者がいちばん
// 早く読む場所である。実際のさくらのサーバーで発行を通したことはまだ無いので、
// 他の文書と同じ「確認できていない」に揃える（掟1・掟9）。
export function dnsGuidanceLines(host: string): string[] {
  const shown = host.trim() || 'ホスト名'
  return [
    `⚠️ この IP をブラウザで直接開くと「404 page not found」になります。ロードバランサは入力されたホスト名でアプリを振り分けるため、必ず https://${shown}/ のように、上のアドレス（ホスト名）で開いてください。`,
    'https は、DNS の A レコードを向けたあとに使えるようになる見込みです（証明書は Let\'s Encrypt が自動で発行します）。それまでは開けません。発行にかかる時間は、実際のさくらのサーバーでまだ確認できていません。',
  ]
}

// publishHeadline — ⑧の公開結果の見出しを1箇所に決める（D-7・2026-09-16 実機で判明）。
//
// 実機（0.6.19-rc.1）で、公開の手続きは全段通ったのに、ロードバランサが
// 503 `no available server` を返し続けていた（＝LB から見て健全なバックエンドが1つも
// 登録されていない。**503 を見た時点でコンテナが起動していたかは、いまも未確認**——同じ日の
// コンパネは「稼働コンテナ 1・アクティブ」と表示していた＝docs/apprun-dedicated-plan.md 5-13）。
// **同じ日の別の時刻（10:34〜10:57）のランタイムログ（D-8）で説明はつく**: コンテナが
// `/app/data` を作れず（`EACCES`）1分ごとに再起動を繰り返していた（像のフォルダが読み取り
// 専用だったのが原因）。**ただし 503 の観測は 08:35 前後で、時刻の突き合わせはしていないので
// 断定はしない**（計画書 5-13・roadmap と同じ基準・掟1）。
// それでも画面は「✅ 公開しました」と出していたため、利用者は応答しないアプリのために
// DNS を設定しに行くことになる。**確かめていないことを「大丈夫」に倒さない。**
//
// そこで⑧は公開のあとに応答を確かめ（publishAppFlow の verify 段）、その結果で見出しを変える。
// **`no-backend`（503＝アプリがまだ応答していない）と `error-status`（404・502・504 …＝
// 失敗応答が返った・D-19b の検分）のとき**、見出しを警告に倒す。
// `stale`／`responding`／`unreachable`／未確認（当てに行く先が無くてとばした）は、公開の
// 手続き自体は通っているので「✅ 公開しました」のまま——ただし画面は dedicatedVerifyMessage の
// 一文を必ず添える（publishVerify.ts。黙って成功に見せない）。
// D-19: `responding`（Node アプリ等で、根へ当てて応答があった）は**成功の見た目でよい**。
// ただし一文のほうは「中身が新しいかまでは確かめていません」と断らせる——
// **見出しで安心させ、一文で正確に言う**の役割分担は、`stale` のときと同じ。
// 判断はここに置き、画面（AppRunDedicatedPanel.tsx）は描くだけにする（掟10）。
// B（D-7b・検分の指摘）: この見出しも素の `<p>` にそのまま流れ、Markdown を解釈しない。
// `**` を混ぜると記号がそのまま画面に出るため使わない（強調は絵文字と呼び出し側の色・太字クラスに
// 任せる。理由は publishVerify.ts 冒頭のコメントと同じ）。
export function publishHeadline(
  verify: DedicatedVerifyOutcome | null | undefined,
): { text: string; tone: 'ok' | 'warn' } {
  if (verify === 'no-backend') {
    return { text: '⚠️ 公開の手続きは通りましたが、アプリがまだ応答していません', tone: 'warn' }
  }
  // D-19b（2026-09-16 の検分）: 404・502・504 のような**失敗応答**も、見出しを警告に倒す。
  // 直す前は「503 以外の応答はすべて `responding`」だったため、**ホスト名の振り分けが効かず
  // LB が 404 を返している**ときでも「✅ 公開しました」＋「✅ アプリが応答することを確認しました」
  // が出ていた（利用者から見てページは開けない）。**届いたことを、開けることの証拠にしない。**
  // 「応答していません」とは書かない——応答は返っている（返ってきたのがエラーである）。
  if (verify === 'error-status') {
    return { text: '⚠️ 公開の手続きは通りましたが、公開先がエラーを返しています', tone: 'warn' }
  }
  return { text: '✅ 公開しました', tone: 'ok' }
}

// ephemeralDataNote — ⑧の説明に添える「書いたデータは残らない」の注意（D-8・2026-09-16）。
//
// D-8 で像のフォルダに書き込みを与えた（imageBuild.ts の copyTree）。アプリは自分でフォルダや
// ファイルを作れるようになるが、**コンテナは使い捨てで、起動のたびに像から作り直される**ので、
// そこへ書いたものは残らない。書けるようになった直後に「入力が保存できる」と
// 思わせるほうが害が大きいので、同じ節に必ず併記する（確かめていないことを都合よく倒さない・掟10）。
//
// ── 「公開し直すと消えます」だけでは弱すぎる（検分の指摘・2026-09-16）──────────────
// 最初の文面は消える条件を**公開し直したとき**だけに限っていた。だが同じ日の実機で、
// コンテナは**自分で再起動していた**（`EACCES` で1分ごと。5-13）。コンテナが入れ替われば、
// 公開し直さなくても像から作り直される＝書いたものは消える。**事実より弱い約束をしない。**
// あわせて、⑧の詳細設定で台数を2以上にすると**コンテナごとに別のデータ**になる（共有されない）
// ことにも触れる。非エンジニアは「公開し直さなければ残る」と読むため、ここを曖昧にしない。
// 文言は1か所（ここ）に持ち、画面は描くだけ。素の `<p>` に流れるので Markdown（`**`）は使わない。
//
// ── 「再起動したとき」が利用者の操作だと読めてしまう（D-13 E・2026-09-16）─────────────
// 非エンジニアには「コンテナが再起動したときも作り直されます」が
// **「自分が再起動しなければ残る」**と読める。実際は**利用者が何もしなくても入れ替わる**
// （2026-09-16 の実機では1分ごとに入れ替わっていた）。そこで「あなたが何もしなくても
// 入れ替わることがあり」を主語のはっきりした形で入れる。**頻度（1分ごと）は書かない**——
// あれは `EACCES` の不具合によるもので、いつもそうなるとは確かめていない（掟1）。
//
// ── 共用型・専有型のどちらの画面からも呼ばれる（D-13 F・2026-09-16）──────────────
// 以前の末尾は「共用型の『保存場所』のような仕組みが要ります」で、**専有型から見た言い方**
// だった。共用型の公開画面（AppRunPanel.tsx）でも同じ1文を出すため、どちらで読んでも
// 通じる言い方にする（文言を複製せず、この関数を両方から呼ぶ・掟10）。
export function ephemeralDataNote(): string {
  return 'アプリが自分のフォルダに書いたデータは残りません。アプリを動かしている入れもの（コンテナ）は使い捨てで、公開し直したときだけでなく、あなたが何もしなくても入れ替わる（再起動する）ことがあり、そのたびに中身は公開したときの状態へ戻ります（台数を2以上にすると、コンテナごとに別のデータになります）。入力を残したいときは、「保存場所」（オブジェクトストレージ）やデータベースのような、入れものの外に残る仕組みが要ります。'
}

// containerStateSummary — ⑧の「いまのコンテナの様子」を1行にする（D-8・2026-09-16 実機）。
//
// verify が `no-backend`（503）のとき、Koto はこれまで「アプリがまだ応答していません。
// ランタイムログを見てください」としか言えなかった。実機では、コンテナが `/app/data` を
// 作れずに **1分ごとに再起動を繰り返していた**（docs/apprun-dedicated-plan.md 5-13）。
// そこで `GET /applications/{id}/containers` を1回だけ引き、その様子をここで一文にする。
//
// **状態の文字列（state・status）は原本の値をそのまま出す。日本語へ言い換えない**——
// 全ての値を実測したわけではないので、勝手な対訳は嘘になりうる（掟1）。
// 同じ `state（status）` が複数あるときは「× 台数」にまとめる（台数が多いときに読めなくなるため）。
// 判断はここに置き、画面（AppRunDedicatedPanel.tsx）は描くだけ（掟10）。
// 見出しと同じく素の `<p>` に流れるので Markdown（`**`）は使わない。
//
// ── 0件と「分からない」を言い分ける（検分の指摘・2026-09-16）────────────────────────
// 以前はここが `null`／`undefined` も 0 件と同じ文に倒しており、**引けなかったことを
// 「1つも動いていません」と断定**していた（D-7 の `unknown-read-as-ok` と同じ形）。
// いまは呼び出し側（publishAppFlow）が、引けなかったとき・応答が原本の形でなかったときに
// `containerStates` を**付けない**ので、画面もこの関数も本来そこには来ない。それでも
// **間違って渡されたときに嘘を言わない**よう、ここでも「読み取れませんでした」に倒す。
// 「取得できませんでした」だけだと**0件と同じに読まれうる**ので、
// **何台動いているかが分からない**ことをその場で書く（0件に倒さないのが要点）。
// **理由（応答の形が違う／HTTP が失敗した）はここでは書かない**——この関数に渡ってくる
// `null` がどちらの理由かは分からないので、書けば新しい断定を1つ増やすことになる（掟1）。
// 理由は呼び出し側が warnings に1行で残している（apprunDedicatedAppApply.ts の 12.5）。
export function containerStateSummary(
  states: { state: string; status: string }[] | null | undefined,
): string {
  // 配列ですらない＝何台動いているかは分からない。**0件に倒さない。**
  if (!Array.isArray(states)) return 'いまのコンテナの様子を読み取れませんでした（何台動いているかは分かりません）。'
  const list = states
  // 0件＝どのノードでもコンテナが動いていない。**「取得できなかった」ではなく「動いていない」**
  // （原本の形で読めた結果が0件のときだけ、呼び出し側がここへ空配列を渡す）。
  if (list.length === 0) return 'コンテナが1つも動いていません。'
  const counts = new Map<string, number>()
  for (const s of list) {
    const key = `${s.state}（${s.status}）`
    counts.set(key, (counts.get(key) ?? 0) + 1)
  }
  const parts = [...counts.entries()].map(([k, n]) => (n > 1 ? `${k} × ${n}` : k))
  return `いまのコンテナの様子: ${parts.join('・')}`
}

// showDnsGuidanceExpanded — DNS の案内（IP・コピー・dnsGuidanceLines）を最初から開いて見せてよいか
// （純関数・D-7b・C・検分の指摘）。
//
// 2026-09-16 の実害は「応答しないアプリのために DNS を設定しに行った」こと。verify が `no-backend`
// （503＝アプリがまだ応答していない）のときは、次の一手を1つに絞る——まず
// dedicatedVerifyMessage が案内する「コントロールパネルの『アプリケーション → ランタイムログ』を
// 見てください」を先に読んでもらい、DNS の設定は応答を確かめたあとでよいと伝える。そのため
// `no-backend` のときだけ false を返し、画面はこれを `<details>`（閉じた状態）に畳む材料にする。
// それ以外（ok/responding/error-status/stale/unreachable・確認をとばした未確認）は、公開の手続き
// 自体は通っているので従来どおり開いたまま見せる。
// D-19b（検分）: `error-status`（404・502・504 …）は、見出しこそ警告に倒すが**ここでは畳まない**。
// 専有型の LB は**ホスト名の振り分けが効かないと 404 を返す**（2026-09-16 実機）ので、
// 404 のときに次に読むべきものは、まさにこの DNS・ホスト名の案内だからである。
// 判断はここに集約し、画面（AppRunDedicatedPanel.tsx）は描くだけ（掟10）。
export function showDnsGuidanceExpanded(verify: DedicatedVerifyOutcome | null | undefined): boolean {
  return verify !== 'no-backend'
}
